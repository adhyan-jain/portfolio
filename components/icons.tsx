/** Maps a config `icon` string onto a glyph; unknown names fall back to a link. */
export function SocialIcon({ name }: { name: string }) {
  switch (name) {
    case "github":
      return <GitHubIcon />;
    case "linkedin":
      return <LinkedInIcon />;
    case "x":
      return <XIcon />;
    case "resume":
      return <ResumeIcon />;
    case "email":
      return <MailIcon />;
    default:
      return <LinkIcon />;
  }
}
